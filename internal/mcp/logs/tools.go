package logs

import "github.com/mark3labs/mcp-go/mcp"

var GetLogsTool = mcp.NewTool("get_logs",
	mcp.WithTitleAnnotation("Get Logs"),
	mcp.WithDescription("Retrieves various types of logs for a component deployment track within a specified project and environment. This unified tool can fetch application logs (from the component itself), build logs (from the build process), gateway logs (from the API gateway), or execution logs (for task runs). PRE-CONDITION: For 'build' logs, a 'build_status_run_id' is required. You can obtain this from the 'get_builds' tool. PRE-CONDITION: For 'execution' logs, an 'execution_id' is required. You can obtain this from the 'get_executions' tool."),
	mcp.WithReadOnlyHintAnnotation(true),
	mcp.WithDestructiveHintAnnotation(false),
	mcp.WithIdempotentHintAnnotation(false),
	mcp.WithOpenWorldHintAnnotation(true),
	mcp.WithString("integration_uuid",
		mcp.Required(),
		mcp.Description("The UUID of the component."),
	),
	mcp.WithString("project_uuid",
		mcp.Required(),
		mcp.Description("The UUID of the project containing the component."),
	),
	mcp.WithString("environment_uuid",
		mcp.Required(),
		mcp.Description("The UUID of the environment."),
	),
	mcp.WithString("component_deployment_track_id",
		mcp.Required(),
		mcp.Description("The ID of the deployment track (e.g., 'Development', 'Production') of the component."),
	),
	mcp.WithString("log_type",
		mcp.Required(),
		mcp.Description("The type of logs to retrieve. Valid values: 'application', 'build', 'gateway', 'execution'. Scope differs by integration subtype: 'application' and 'build' work for all six subtypes; 'gateway' applies to the HTTP-serving subtypes ('API', 'AI Agent', 'MCP Server'); 'execution' applies ONLY to 'Automation' (a scheduled task), since it is the only subtype with executions — requesting it for anything else returns an error, so use 'application' instead."),
	),
	mcp.WithString("build_status_run_id",
		mcp.Description("Required if 'log_type' is 'build'. The RunId of the build."),
	),
	mcp.WithString("execution_id",
		mcp.Description("Required if 'log_type' is 'execution'. The ID of the task execution."),
	),
)
