package build

import "github.com/mark3labs/mcp-go/mcp"

var GetBuildsTool = mcp.NewTool("get_builds",
	mcp.WithTitleAnnotation("Get Builds"),
	mcp.WithDescription("Retrieves a list of all builds for a specific component. This includes information about the build status (in_progress, queued, completed, failed), associated git commit details, and image IDs. Use this to monitor build progress or find specific build IDs for deployment or log retrieval."),
	mcp.WithReadOnlyHintAnnotation(true),
	mcp.WithDestructiveHintAnnotation(false),
	mcp.WithIdempotentHintAnnotation(false),
	mcp.WithOpenWorldHintAnnotation(true),
	mcp.WithString("project_uuid",
		mcp.Required(),
		mcp.Description("The UUID of the project containing the component."),
	),
	mcp.WithString("integration_uuid",
		mcp.Required(),
		mcp.Description("The UUID of the component to get builds from."),
	),
	mcp.WithString("component_deployment_track_id",
		mcp.Required(),
		mcp.Description("The ID of the deployment track (e.g., Development, Production) to get builds from."),
	),
	mcp.WithBoolean("wait_for_completion",
		mcp.Description("If true, the tool will wait until the build process completes before returning the result. If false, the tool returns immediately with current build status, allowing other tasks to be performed while the build continues running in the background."),
		mcp.DefaultBool(false),
	),
)

var GetCommitHistoryTool = mcp.NewTool("get_commit_history",
	mcp.WithTitleAnnotation("Get Commit History"),
	mcp.WithDescription("Retrieves the commit history for a specific component's repository branch. This can be useful for identifying commit hashes for builds or understanding recent changes."),
	mcp.WithReadOnlyHintAnnotation(true),
	mcp.WithDestructiveHintAnnotation(false),
	mcp.WithIdempotentHintAnnotation(false),
	mcp.WithOpenWorldHintAnnotation(true),
	mcp.WithString("integration_uuid",
		mcp.Required(),
		mcp.Description("The UUID of the component to get commit history from."),
	),
	mcp.WithString("branch",
		mcp.Required(),
		mcp.Description("The branch (e.g., 'main', 'feature-branch') to get the commit history from."),
	),
)

var CreateBuildTool = mcp.NewTool("create_build",
	mcp.WithTitleAnnotation("Create Build"),
	mcp.WithDescription("Initiates a new build process for a specific component. This tool takes a git commit hash and the component's deployment track to create a new version of the component's deployable artifact (image). You can monitor the build progress using the get_builds tool."),
	mcp.WithReadOnlyHintAnnotation(false),
	mcp.WithDestructiveHintAnnotation(false),
	mcp.WithIdempotentHintAnnotation(false),
	mcp.WithOpenWorldHintAnnotation(true),
	mcp.WithString("integration_uuid",
		mcp.Required(),
		mcp.Description("The UUID of the component for which to create the build."),
	),
	mcp.WithString("project_uuid",
		mcp.Required(),
		mcp.Description("The UUID of the project containing the component."),
	),
	mcp.WithString("component_deployment_track_id",
		mcp.Required(),
		mcp.Description("The ID of the deployment track (e.g., 'Development', 'Production') for which the build is intended."),
	),
	mcp.WithString("branch",
		mcp.Required(),
		mcp.Description("The branch (e.g., 'main', 'feature-branch') to get the commit history from."),
	),
	mcp.WithString("commit_hash",
		mcp.Description("The git commit's full hash associated with the build being deployed. If not provided, the latest commit hash will be used."),
	),
)
