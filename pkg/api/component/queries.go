// TODO: move to a separate util and replace all the gql queries with this
// wrapper for gql query
func wrapQuery(query string) string {
	return `{"query": "` + query + `"}`
}

func sanitizeString(input string) string {
	reg, _ := regexp.Compile("[^a-zA-Z0-9]+")
	processedString := reg.ReplaceAllString(strings.ToLower(strings.TrimSpace(input)), "-")
	return processedString
}

