func (c *GraphQLClient) getUpdateCodeServerQuery(
	userId string,
	organizationId string,
	projectId string,
	componentId string,
	orgHandle string,
	imageUrl string,
	registryId string,
	sourceCommitHash string,
) (string, error) {

	query := fmt.Sprintf(`mutation{ updateCodeServer(
      input: {
        userId: \"%s\",
        organizationId: \"%s\",    
        projectId: \"%s\",
        componentId: \"%s\",
        orgHandle:\"%s\",
        imageUrl: \"%s\",
        registryId: \"%s\",
        sourceCommitHash: \"%s\"
      })}`, userId, organizationId, projectId, componentId, orgHandle, imageUrl, registryId, sourceCommitHash)

	return wrapQuery(query), nil
}
