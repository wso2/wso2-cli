func GetDeleteProjectQuery(orgId string, projectId string) string {
	return wrapQuery(fmt.Sprintf(`
		mutation{ 
			deleteProject(orgId: %s, projectId: \"%s\"){
				status,
				details 
			} 
		}
	`, orgId, projectId))
}

