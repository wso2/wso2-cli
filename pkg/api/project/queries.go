package project

import "fmt"

// wrapper for gql query
func wrapQuery(query string) string {
	return `{"query": "` + query + `"}`
}

// Get Projects by Org ID
func GetProjectsByOrgIDQuery(orgID string) string {
	return wrapQuery(`query { projects(orgId: ` +
		orgID +
		`) { id, orgId, name, version, createdDate, handler, region, description, repository, branch, gitProvider, gitOrganization } }`)
}

func GetProjectEnvironmentsQuery(orgUuid string, projectId string) string {
	query := fmt.Sprintf(`query { environments(orgUuid:\"%s\", projectId:\"%s\"){ name, id, choreoEnv, vhost, apiEnvName, isMigrating, apimEnvId, namespace, sandboxVhost, critical, isPdp, promoteFrom, dpId, templateId } }`,
		orgUuid,
		projectId,
	)
	return wrapQuery(query)
}

